export function scoreQuestionnaire(
  q: QuestionnaireDef,
  answers: number[]
): { dims: DimensionResult[]; flags: ResultFlag[] } {
  const { min, max } = q.scale;
  const mult = q.mult || 1;
  const raw: Record<string, number> = {};
  q.items.forEach((it, i) => {
    const d = it[1];
    const rev = it[2];
    let v = answers[i] ?? min;
    if (rev) v = min + max - v;
    raw[d] = (raw[d] || 0) + v;
  });
  const dims: DimensionResult[] = [];
  const scMap: Record<string, { value: number }> = {};
  Object.keys(q.dims).forEach((k) => {
    const n = q.items.filter((it) => it[1] === k).length;
    const lo = n * min * mult;
    const hi = n * max * mult;
    const val = (raw[k] || 0) * mult;
    const b = band(q.dims[k].bands, val);
    scMap[k] = { value: val };
    dims.push({
      name: q.dims[k].name,
      display: `${val} / ${hi}`,
      pct: hi > lo ? (val - lo) / (hi - lo) : 0,
      label: b.label,
      tone: b.tone,
      text: b.text,
    });
  });
  const flags = q.flags ? q.flags(answers, scMap) : [];
  return { dims, flags };
}

