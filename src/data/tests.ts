export function interpStroop(raw: Record<string, unknown>) {
  const a = (raw.a as Array<{ rt: number; ok: boolean }>) || [];
  const b = (raw.b as Array<{ rt: number; ok: boolean }>) || [];
  const okA = a.filter((x) => x.ok);
  const okB = b.filter((x) => x.ok);
  const ma = mean(okA.map((x) => x.rt));
  const mb = mean(okB.map((x) => x.rt));
  const inter = mb - ma;
  const accA = a.length ? (okA.length / a.length) * 100 : 0;
  const accB = b.length ? (okB.length / b.length) * 100 : 0;
  const d1 = band(
    [
      B(150, 'خوب', 'good', 'توجه انتخابی و مهار پاسخ خودکار بسیار خوب.'),
      B(250, 'متوسط', 'mid', 'اثر تداخل در حد متوسط.'),
      B(
        99999,
        'بالا',
        'warn',
        'دشواری در مهار پاسخ خودکار و توجه انتخابی؛ در مشاغل نیازمند کنترل همزمان چند محرک احتیاط شود.'
      ),
    ],
    inter
  );
  const d2 =
    accB >= 94
      ? { label: 'دقت بالا', tone: 'good' as Tone, text: 'خطای بسیار کم در شرایط تداخل.' }
      : accB >= 85
      ? { label: 'متوسط', tone: 'mid' as Tone, text: 'دقت قابل قبول.' }
      : { label: 'دقت پایین', tone: 'warn' as Tone, text: 'خطای زیاد در شرایط تداخل؛ افت تمرکز یا تکانشگری.' };
  const flags: ResultFlag[] = [];
  if (accA < 80) {
    flags.push({
      tone: 'warn',
      text: 'دقت در تشخیص ساده‌ی رنگ پایین بود؛ معاینه‌ی دید رنگ (آزمون ایشی‌هارا) در طب کار توصیه می‌شود.',
    });
  }
  return {
    dims: [
      {
        name: 'اثر تداخل استروپ (RT ناهمخوان − همخوان)',
        display: `${Math.round(inter)} ms`,
        pct: clamp01(inter / 400),
        ...d1,
      },
      {
        name: 'دقت در مرحله‌ی تداخل',
        display: `${Math.round(accB)}٪`,
        pct: clamp01(accB / 100),
        ...d2,
      },
      {
        name: 'سرعت پردازش رنگ پایه',
        display: `${Math.round(ma)} ms`,
        pct: clamp01((ma - 300) / 900),
        label: 'اطلاعاتی',
        tone: 'info' as Tone,
        text: 'سرعت پایه ادراک رنگ.',
      },
    ],
    flags,
  };
}

