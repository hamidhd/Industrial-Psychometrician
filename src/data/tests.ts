export const clamp01 = (x: number) => Math.max(0, Math.min(1, x));
export const mean = (a: number[]) => (a.length ? a.reduce((x, y) => x + y, 0) / a.length : 0);
export const sd = (a: number[]) => {
  if (a.length < 2) return 0;
  const m = mean(a);
  return Math.sqrt(mean(a.map((x) => (x - m) ** 2)));
};
export const shuffle = <T,>(arr: T[]): T[] => {
  const a = arr.slice();
  for (let i = a.length - 1; i > 0; i--) {
    const j = Math.floor(Math.random() * (i + 1));
    [a[i], a[j]] = [a[j], a[i]];
  }
  return a;
};

export function band(bands: BandDef[], v: number): BandDef {
  for (const item of bands) {
    if (v <= item.upTo) return item;
  }
  return bands[bands.length - 1];
}

export const faDigits = (s: string | number) =>
  String(s).replace(/\d/g, (d) => '۰۱۲۳۴۵۶۷۸۹'[Number(d)]);

export const jdate = (t: number) => {
  try {
    return new Date(t).toLocaleDateString('fa-IR');
  } catch {
    return '';
  }
};

export const jdt = (t: number) => {
  try {
    return (
      new Date(t).toLocaleDateString('fa-IR') +
      ' ' +
      new Date(t).toLocaleTimeString('fa-IR', { hour: '2-digit', minute: '2-digit' })
    );
  } catch {
    return '';
  }
};

